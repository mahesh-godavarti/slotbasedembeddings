"""Token-matched comparison of D=x vs N=x models.

For each (N, D) pair, computes total tokens at each D eval point,
interpolates N's PPL at that token count, and shows the gap.

Supports Claim 1: D beats N at matched tokens and the gap widens.
"""

import sys


def interp(points, target):
    """Interpolate PPL at target token count from sorted (tok, ppl) list."""
    for i in range(len(points) - 1):
        t1, p1 = points[i]
        t2, p2 = points[i + 1]
        if t1 <= target <= t2:
            frac = (target - t1) / (t2 - t1)
            return p1 + frac * (p2 - p1)
    return None


def token_matched_table(name, n_evals, n_tok_per_iter, d_evals, d_tok_per_iter, d_pretrain, sparse=True):
    """Print token-matched comparison table."""
    n_points = [(it * n_tok_per_iter / 1e6, ppl) for it, ppl in n_evals]
    d_points = [(d_pretrain / 1e6 + it * d_tok_per_iter / 1e6, ppl) for it, ppl in d_evals]

    print(f"\n{'='*60}")
    print(f"  {name}")
    print(f"{'='*60}")
    print(f"{'Total tokens (M)':>18} {'N PPL':>10} {'D PPL':>10} {'Gap':>8}")
    print('-' * 50)

    results = []
    for tok, d_ppl in d_points:
        n_ppl = interp(n_points, tok)
        if n_ppl is not None:
            gap = d_ppl - n_ppl
            results.append((tok, n_ppl, d_ppl, gap))

    if sparse:
        # Show ~20 evenly spaced points
        step = max(1, len(results) // 20)
        results = results[::step]
        # Always include last point
        last = [(tok, n_ppl, d_ppl, gap) for tok, n_ppl, d_ppl, gap in
                [(d_pretrain / 1e6 + it * d_tok_per_iter / 1e6, interp(n_points, d_pretrain / 1e6 + it * d_tok_per_iter / 1e6), ppl, None)
                 for it, ppl in d_evals] if n_ppl is not None]

    for tok, n_ppl, d_ppl, gap in results:
        print(f'{tok:>18.0f} {n_ppl:>10.1f} {d_ppl:>10.1f} {gap:>+8.1f}')

    # Summary
    crossover = None
    for tok, n_ppl, d_ppl, gap in [(tok, n_ppl, d_ppl, d_ppl - n_ppl)
                                    for tok, d_ppl in d_points
                                    if (n_ppl := interp(n_points, tok)) is not None]:
        if gap < 0 and crossover is None:
            crossover = tok

    last_matched = [(tok, d_ppl - interp(n_points, tok))
                    for tok, d_ppl in d_points
                    if interp(n_points, tok) is not None]
    if last_matched:
        final_tok, final_gap = last_matched[-1]
        print(f"\nCrossover at ~{crossover:.0f}M tokens" if crossover else "\nNo crossover yet")
        print(f"Final gap at {final_tok:.0f}M tokens: {final_gap:+.1f} PPL")

    return results


